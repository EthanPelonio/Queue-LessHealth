public class User {

    String name;
    String username;
    String password;
    int age;
    String contact;

    public User(
            String name,
            String username,
            String password,
            int age,
            String contact) {

        this.name = name;
        this.username = username;
        this.password = password;
        this.age = age;
        this.contact = contact;
    }
}